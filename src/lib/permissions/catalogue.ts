export type Permission = (typeof PERMISSIONS)[number];

export const hasPermission = (granted: readonly string[], required: Permission): boolean =>
  granted.includes(required);

export function canChangeRoles(granted: readonly string[], current: readonly string[], next: readonly string[]): boolean {
  return (next.every(role => current.includes(role)) || hasPermission(granted, "Users.AssignRoles"))
    && (current.every(role => next.includes(role)) || hasPermission(granted, "Users.RemoveRoles"));
}

export const PERMISSION_MODULES = Object.entries(
  PERMISSIONS.reduce<Record<string, string[]>>((groups, key) => {
    (groups[key.split('.')[0]] ??= []).push(key);
    return groups;
  }, {}),
).map(([module, permissions]) => ({ module, permissions }));
